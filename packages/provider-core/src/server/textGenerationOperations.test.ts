import { assert, describe, it } from "@effect/vitest";
import * as Effect from "effect/Effect";
import * as Schema from "effect/Schema";

import { decodeJsonReply, decodeJsonReplyDetailed } from "./textGenerationOperations.ts";

const request = {
  operation: "generateThreadTitle" as const,
  outputSchema: Schema.Struct({ title: Schema.String, body: Schema.String }),
};

const decode = (text: string) => decodeJsonReplyDetailed(request, text);

describe("decodeJsonReplyDetailed", () => {
  it.effect("uses the last JSON object when the model repeats its answer", () =>
    Effect.gen(function* () {
      const value = yield* decode(
        'Example: {"title":"Draft","body":"first"}\nFinal answer: {"title":"Real","body":"second"}',
      );
      assert.deepEqual(value, { title: "Real", body: "second" });
    }),
  );

  it.effect("accepts comments and trailing commas without a repair", () =>
    Effect.gen(function* () {
      const value = yield* decode(`{
        // generated by the model
        "title": "Real",
        "body": "second",
      }`);
      assert.deepEqual(value, { title: "Real", body: "second" });
    }),
  );

  it.effect("names a truncated object instead of a generic parse failure", () =>
    Effect.gen(function* () {
      const failure = yield* Effect.flip(decode('Here you go: {"title":"Real","body":'));
      assert.include(failure.reason, "unterminated");
      assert.include(failure.reason, "likely truncated");
    }),
  );

  it.effect("reports the field that missed the schema", () =>
    Effect.gen(function* () {
      const failure = yield* Effect.flip(decode('{"title":42,"body":"second"}'));
      assert.include(failure.reason, "did not match the expected shape");
      assert.include(failure.reason, '["title"]');
    }),
  );

  it.effect("reports a reply with no JSON object", () =>
    Effect.gen(function* () {
      const failure = yield* Effect.flip(decode("I cannot help with that."));
      assert.equal(failure.reason, "the reply contained no JSON object");
    }),
  );
});

describe("decodeJsonReply", () => {
  it.effect("keeps the provider and the reason in the error detail", () =>
    Effect.gen(function* () {
      const error = yield* Effect.flip(decodeJsonReply(request, "Pi", "I cannot help with that."));
      assert.equal(
        error.detail,
        "Pi returned invalid structured output: the reply contained no JSON object.",
      );
    }),
  );
});
